"""Pure migration of repeated facts and evidence bindings; never writes files.

Run stable-reference migration, then reviewed credit migration, before this step.
The caller reviews returned data and owns any write. Rebinding preserves a
source's evidence claim, not its truth: excerpts still require editorial review
against their new primary leaves.
"""

import copy

if __package__:
    from .published import (
        announcement,
        first_designation,
        naming_act,
        first_output,
        materialise_facts,
        status_basis,
        component_indices,
        current_allocation,
    )
    from .references import stable_selector, support_pointer
else:
    from published import (
        announcement,
        first_designation,
        naming_act,
        first_output,
        materialise_facts,
        status_basis,
        component_indices,
        current_allocation,
    )
    from references import stable_selector, support_pointer


def migrate(document: dict, *, manifest: list[dict] | None = None) -> dict:
    """Return primary facts, optionally appending changed excerpt bindings on success.

    Manifest entries expose old references and new stable selectors for evidence
    review; they do not certify that the quotation supports the new claim.
    """
    for institute in document.get("institutes", []):
        for item in institute.get("outputs", []):
            if "credit" not in item:
                raise ValueError(
                    f"{institute['id']}/{item['lineage']}: reviewed credit is required; "
                    "run stable-reference migration, then reviewed credit migration, "
                    "before facts migration"
                )
    materialise_facts(document)  # Never conceal an existing repeated-fact conflict.
    data = copy.deepcopy(document)
    replacements = {}
    review_required = {}
    computed_targets = set()
    changes = []
    removals = []
    jurisdictions = {
        j["id"]: (n, j) for n, j in enumerate(data.get("jurisdictions", []))
    }

    def remove(record, field, path, targets):
        if field in record:
            replacements[f"{path}/{field}"] = targets
            removals.append((record, field))

    def event_pointer(jn, events, event, leaf):
        return f"/jurisdictions/{jn}/timeline/{events.index(event)}/{leaf}"

    def computed_evidence(pointer, reason):
        review_required[pointer] = reason
        computed_targets.add(pointer)

    for jn, jurisdiction in jurisdictions.values():
        events = jurisdiction.get("timeline", [])
        _, _, basis_index = status_basis(events)
        basis = events[basis_index] if basis_index is not None else None
        path = f"/jurisdictions/{jn}"
        # A no-institute result with no timeline has no positive act to cite.
        # Any support explicitly bound to that result fails below for review.
        for field, leaf in (("status", "event"), ("status_since", "date")):
            targets = [event_pointer(jn, events, basis, leaf)] if basis else []
            remove(jurisdiction, field, path, targets)

    for n, institute in enumerate(data.get("institutes", [])):
        jn, jurisdiction = jurisdictions[institute["jurisdiction_id"]]
        events = jurisdiction.get("timeline", [])
        path = f"/institutes/{n}"
        remove(
            institute,
            "status",
            path,
            replacements.get(f"/jurisdictions/{jn}/status", []),
        )
        designation = first_designation(events)
        targets = (
            [event_pointer(jn, events, events[designation], "date")]
            if designation is not None else []
        )
        remove(institute, "established", path, targets)
        announced = announcement(events, data.get("dataset", {}).get("as_of"))
        targets = (
            [event_pointer(jn, events, events[announced], "date")]
            if announced is not None else []
        )
        remove(institute, "announced", path, targets)
        # materialise_facts above already rejects a name without its event.
        for k, name in enumerate(institute.get("names", [])):
            act = events[naming_act(events, name)]
            remove(name, "from", f"{path}/names/{k}", [event_pointer(jn, events, act, "date")])
        remove(institute, "operating", path, [])
        # Generated by materialise_facts from the access events, power and agreements.
        for field in ("value", "latest_event"):
            if "model_access" in institute:
                remove(institute["model_access"], field, f"{path}/model_access", [])
        records = institute.get("funding", [])
        for fn, funding in enumerate(records):
            fp = f"{path}/funding/{fn}"
            if "sum_of" in funding:
                indices = component_indices(records, fn)
                for key in ("amount", "annual_amount"):
                    computed_evidence(f"{fp}/{key}", "sum_of evidence needs review")
                    remove(
                        funding,
                        key,
                        fp,
                        [f"{path}/funding/{child}/{key}" for child in indices],
                    )
            elif funding.get("annual_basis_code") == "period_mean":
                computed_evidence(
                    f"{fp}/annual_amount", "period_mean evidence needs review"
                )
                remove(funding, "annual_amount", fp, [f"{fp}/amount", f"{fp}/years"])
            elif funding.get(
                "annual_basis_code"
            ) == "allocation_current_year" and funding.get("annual_profile"):
                allocation = current_allocation(funding, data["dataset"]["as_of"])
                profile = f"{fp}/annual_profile/{allocation}"
                remove(funding, "annual_amount", fp, [f"{profile}/amount"])
                remove(
                    funding, "annual_period", fp, [f"{profile}/start", f"{profile}/end"]
                )
                for key in ("start", "end"):
                    replacements[f"{fp}/annual_period/{key}"] = [f"{profile}/{key}"]
            computed_evidence(
                f"{fp}/eur_per_year_est", "EUR annual conversion evidence needs review"
            )
            remove(
                funding,
                "eur_per_year_est",
                f"{path}/funding/{fn}",
                [f"{path}/funding/{fn}/annual_amount"],
            )
        for on, item in enumerate(institute.get("outputs", [])):
            op = f"{path}/outputs/{on}"
            # Credit identity bindings are supplied only by the reviewed credit
            # migration. Editorial attribution is not evidence of institute credit.
            if "credited_from" in item:
                remove(item, "credited_from", op, [f"{op}/credit/date"])
        output = first_output(institute)
        for en, event in enumerate(events):
            if event["event"] != "first_output":
                continue
            if output is None:  # materialise_facts already rejects this.
                raise ValueError(f"{institute['id']}: first_output has no output")
            op = f"{path}/outputs/{institute['outputs'].index(output)}"
            date = "date" if event["date"] == output["date"] else "credit/date"
            leaves = {
                "date": [date],
                "description": ["title"],
                "short": ["title"],
                "instrument": ["type"],
                "output_lineage": ["lineage"],
            }
            ep = f"/jurisdictions/{jn}/timeline/{en}"
            for pointer in (ep, f"{ep}/event", f"{ep}/id", f"{ep}/source_ids"):
                review_required[pointer] = (
                    "first_output evidence needs review; only reviewed credit "
                    "assignments may bind institutional credit identity"
                )
            replacements.update(
                {
                    f"{ep}/{key}": [f"{op}/{leaf}" for leaf in values]
                    for key, values in leaves.items()
                }
            )

    for n, row in enumerate(data.get("dataset", {}).get("exchange_rates", [])):
        path = f"/dataset/exchange_rates/{n}"
        computed_evidence(f"{path}/eur_per_unit", "EUR rate evidence needs review")
        remove(row, "eur_per_unit", path, [f"{path}/units_per_eur"])

    def rebind(reference):
        pointer = support_pointer(data, reference)

        def expand(pointer, seen=()):
            if pointer in review_required:
                raise ValueError(f"{pointer}: {review_required[pointer]}")
            if pointer in seen:
                raise ValueError(f"{pointer}: cyclic evidence replacement")
            targets = replacements.get(pointer)
            if targets is None:
                return [pointer]
            return [
                leaf for target in targets for leaf in expand(target, (*seen, pointer))
            ]

        targets = expand(pointer)
        if not targets:
            raise ValueError(
                f"{pointer}: no primary fact to rebind; review its evidence"
            )
        return [stable_selector(data, target) for target in targets]

    def rebound_unique(references, context=None):
        result = []
        for reference in references:
            rebound = rebind(reference)
            if context is not None and rebound != [reference]:
                changes.append(
                    copy.deepcopy(
                        {
                            **context,
                            "old_reference": reference,
                            "old_pointer": support_pointer(data, reference),
                            "new_selectors": rebound,
                        }
                    )
                )
            for selector in rebound:
                if selector not in result:
                    result.append(selector)
        return result

    for source in data.get("sources", []):
        for index, excerpt in enumerate(source.get("excerpts", [])):
            excerpt["supports"] = rebound_unique(
                excerpt["supports"],
                {
                    "source_id": source["id"],
                    "excerpt_index": index,
                    "text": excerpt.get("text"),
                },
            )
    claims = []
    for claim in data.get("dataset", {}).get("shared_claims", []):
        previous_count = len(claim["targets"])
        # Equality checks on removed computed copies are obsolete. Their targets
        # are not quotations and must not be retargeted to different quantities.
        retained = [
            target
            for target in claim["targets"]
            if support_pointer(data, target) not in computed_targets
        ]
        claim["targets"] = rebound_unique(retained)
        # A registry entry comparing only a removed copy to its input is obsolete.
        if not (previous_count >= 2 and len(claim["targets"]) < 2):
            claims.append(claim)
    if "shared_claims" in data.get("dataset", {}):
        data["dataset"]["shared_claims"] = claims
    for record, field in removals:
        record.pop(field)
    for jurisdiction in data.get("jurisdictions", []):
        if "timeline" in jurisdiction:
            jurisdiction["timeline"] = [
                e for e in jurisdiction["timeline"] if e["event"] != "first_output"
            ]
    materialise_facts(data, strict=True)
    if manifest is not None:
        manifest.extend(changes)
    return data
